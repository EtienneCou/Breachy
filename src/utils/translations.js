/**
 * Fonction d'accès aux traductions : t('home.heroTitle', language)
 */
export function getTranslation(path, lang = 'fr', ...args) {
  const dict = TRANSLATIONS[lang] || TRANSLATIONS.fr;
  const parts = path.split('.');
  let current = dict;

  for (const part of parts) {
    if (current && current[part] !== undefined) {
      current = current[part];
    } else {
      // Fallback en français
      let fallback = TRANSLATIONS.fr;
      for (const fpart of parts) {
        if (fallback && fallback[fpart] !== undefined) fallback = fallback[fpart];
      }
      current = fallback ?? path;
      break;
    }
  }

  if (typeof current === 'function') {
    return current(...args);
  }
  return current ?? path;
}

/**
 * Retourne l'URL du fichier son de Reachy en fonction de la langue
 */
export function getReachyVoiceUrl(soundName, lang = 'fr') {
  const cleanName = soundName.replace(/\.mp3$/, '');
  if (lang === 'en') {
    return `/audio/reachy/en/${cleanName}.mp3`;
  }
  return `/audio/reachy/${cleanName}.mp3`;
}
